local function equal(actual, expected)
  assert(
    vim.deep_equal(actual, expected),
    "Expected " .. vim.inspect(expected) .. ", got " .. vim.inspect(actual)
  )
end
local function put(path, contents)
  vim.fn.mkdir(vim.fs.dirname(path), "p")
  local file = assert(io.open(path, "wb"))
  file:write(contents)
  file:close()
end
local function test(name, fn)
  fn()
  passed = passed + 1
  print("PASS " .. name)
end
local function finish()
  assert(vim.wait(10000, function() return not ui.state.busy end, 10))
end
local function choose(path)
  api.nvim_set_current_win(ui.state.list)
  local parent, parts = "", vim.split(path, "/", { plain = true })
  for index = 1, #parts - 1 do
    parent = parent .. parts[index] .. "/"
    local collapsed = ui.state.all_files and ui.state.project_collapsed or ui.state.collapsed
    if collapsed[parent] then
      for line, row in pairs(ui.state.tree_rows) do
        if row.path == parent then
          api.nvim_win_set_cursor(0, { line, 0 })
          vim.fn.maparg("l", "n", false, true).callback()
          break
        end
      end
    end
  end
  for line, row in pairs(ui.state.tree_rows) do
    if row.path == path then
      api.nvim_win_set_cursor(0, { line, 0 })
      vim.fn.maparg("<CR>", "n", false, true).callback()
      finish()
      return
    end
  end
  error("Missing tree path: " .. path)
end
